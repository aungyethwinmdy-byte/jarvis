def _key(s: str) -> str:
    """Consonant skeleton of a Burmese string — base consonants only."""
    return "".join(
        ch for ch in (s or "")
        if "\u1000" <= ch <= "\u1021" or ch.isascii() and ch.isalnum()
    )


def _matches(asked: str, name: str) -> int:
    """Match quality: 2 = exact, 1 = containment, 0 = no match."""
    squash = lambda s: re.sub(r"\s+", "", s or "")  # noqa: E731
    a, t = squash(asked), squash(name)
    if a and t and a == t:
        return 2
    ka, kt = _key(asked), _key(name)
    if ka and kt:
        if ka == kt:
            return 2
        short = min(len(ka), len(kt))
        if short >= 4 and (ka in kt or kt in ka):
            return 1
    if a and t and (a in t or t in a):
        return 1
    return 0


def _fmt_names(names: list[str]) -> str:
    if not names:
        return "မရှိပါ"
    if len(names) == 1:
        return names[0]
    return "၊ ".join(names[:-1]) + " နှင့် " + names[-1]


def _best(cands: list[tuple[int, str]]) -> list[str]:
    """Keep only candidates at the best match tier found."""
    if not cands:
        return []
    top = max(score for score, _ in cands)
    return [text for score, text in cands if score >= top]


def _search_specific_role(asked: str) -> list[str]:
    """အဖွဲ့အစည်းနှင့် ရာထူးတွဲမေးသောအခါ သက်ဆိုင်ရာ ရာထူးကိုသာ ကွက်တိထုတ်ပေးခြင်း။
    ဥပမာ- 'ရန်ကုန်တိုင်း ဝန်ကြီးချုပ်', 'ကချင် လုံခြုံရေးဝန်ကြီး'
    """
    tokens = [t for t in re.split(r"\s+", asked) if t]
    results: list[str] = []

    # တိုင်းဒေသကြီး/ပြည်နယ်များ အတွက် စစ်ဆေးခြင်း
    for region, posts in _REGIONS:
        r_score = max([_matches(asked, region)] + [_matches(t, region) for t in tokens])
        if r_score > 0:
            for role, holder in posts:
                # မေးခွန်းစာသားထဲတွင် role အမည် ပါ/မပါ စစ်ဆေးခြင်း
                if any(_matches(t, role) for t in tokens if len(_key(t)) >= 3) or (
                    len(_key(role)) >= 3 and _key(role) in _key(asked)
                ):
                    results.append(f"**{region}**\n• {role} — **{holder}**")

    # ပြည်ထောင်စုအဆင့် အဖွဲ့အစည်းများ အတွက် စစ်ဆေးခြင်း
    for body, posts in _UNION_BODIES:
        b_score = max([_matches(asked, body)] + [_matches(t, body) for t in tokens])
        if b_score > 0:
            for role, holder in posts:
                if any(_matches(t, role) for t in tokens if len(_key(t)) >= 3) or (
                    len(_key(role)) >= 3 and _key(role) in _key(asked)
                ):
                    holders = [holder] if isinstance(holder, str) else list(holder)
                    results.append(f"**{body}**\n• {role} — **{_fmt_names(holders)}**")

    return results


def _council_answer(asked: str) -> list[str]:
    out = []
    for role, holder in _COUNCIL:
        score = max(_matches(asked, role), _matches(asked, holder))
        if score:
            out.append((score, f"• {role} — {holder}"))
    return _best(out)


def _union_answer(asked: str) -> list[str]:
    out = []
    tokens = [t for t in re.split(r"\s+", asked) if t]
    for body, posts in _UNION_BODIES:
        score = max([_matches(asked, body)] + [_matches(t, body) for t in tokens])
        if score:
            lines = [f"**{body}**"]
            for role, holder in posts:
                holders = [holder] if isinstance(holder, str) else list(holder)
                lines.append(f"• {role}: {_fmt_names(holders)}")
            out.append((score, "\n".join(lines)))
            continue
        for role, holder in posts:
            holders = [holder] if isinstance(holder, str) else list(holder)
            s = max(max(_matches(asked, h) for h in holders),
                    max([0] + [_matches(t, h) for t in tokens for h in holders]))
            if s:
                out.append((s, f"**{body}** — {role}: {_fmt_names(holders)}"))
    return _best(out)


def _region_answer(asked: str) -> list[str]:
    out = []
    tokens = [t for t in re.split(r"\s+", asked) if t]
    for region, posts in _REGIONS:
        score = max([_matches(asked, region)] + [_matches(t, region) for t in tokens])
        if score:
            lines = [f"**{region}**"]
            lines += [f"• {role}: {holder}" for role, holder in posts]
            out.append((score, "\n".join(lines)))
            continue
        for role, holder in posts:
            s = max([_matches(asked, holder)] + [_matches(t, holder) for t in tokens])
            if s:
                out.append((s, f"{region} — {role}: {holder}"))
    if any(score == 2 for score, _ in out):
        out = [c for c in out if c[0] == 2]
    return _best(out)


def moi_roster(parameters: dict = None, **_) -> str:
    """Answer who holds a post in the council / union bodies / a region.

    The signature is `(parameters, ...)` because core/action_loader.py calls
    a handler as `fn(parameters=parameters, ...)` — a handler that swallows
    the dict in `**_` runs on defaults.
    """
    p = parameters or {}
    asked = str(p.get("name") or p.get("query") or p.get("person") or "").strip()
    if not asked:
        return ("ဘယ်အဖွဲ့အစည်း ဒါမှမဟုတ် နာမည်လဲ ပြောပါ — ဥပမာ "
                "အမျိုးသားကာကွယ်ရေးနှင့် လုံခြုံရေးကောင်စီ၊ မန္တလေးတိုင်း၊ "
                "ဒါမှမဟုတ် ပုဂ္ဂိုလ်နာမည် တစ်ခု မေးနိုင်ပါသည်။")

    # ၁။ အဖွဲ့အစည်း + ရာထူး သီးသန့် ကွက်တိမေးခွန်းများကို အရင် ဦးစားပေးစစ်ဆေးခြင်း
    specific_role_hits = _search_specific_role(asked)
    if specific_role_hits:
        return "\n\n".join(specific_role_hits)

    # ၂။ ကောင်စီ နာမည် အပြည့်အစုံ မေးမြန်းမှု
    council_hits = _council_answer(asked)
    region_hits = _region_answer(asked)
    union_hits = _union_answer(asked)
    if not council_hits and not region_hits and not union_hits:
        tokens = [t for t in re.split(r"\s+", asked) if t]
        if any(_matches(t, _COUNCIL_NAME) and len(_key(t)) >= 4 for t in tokens):
            lines = [f"**{_COUNCIL_NAME}** (အဖွဲ့ဝင် အားလုံး)"]
            lines += [f"• {role} — {holder}" for role, holder in _COUNCIL]
            return "\n".join(lines)

    # ၃။ လူပုဂ္ဂိုလ်နာမည် သို့မဟုတ် အဖွဲ့အစည်း တစ်ခုလုံး စာရင်းပြသခြင်း
    hits = _region_answer(asked) + _union_answer(asked) + _council_answer(asked)
    if hits:
        return "\n".join(hits).strip()

    return (f"⚠️ '{asked}' — စာရင်း ၃ ခုထဲ (ကောင်စီ၊ ပြည်ထောင်စုအဆင့်အဖွဲ့၊ "
            f"တိုင်း/ပြည်နယ်အစိုးရအဖွဲ့) မတွေ့ပါ။ "
            f"အဖွဲ့အစည်း ဒါမှမဟုတ် ပုဂ္ဂိုလ်နာမည် အတိအကျ မေးပါ။")


